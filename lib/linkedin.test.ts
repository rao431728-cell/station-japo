import assert from "node:assert/strict";
import { createEmpty } from "@/data/empty";
import { canonicalLinkedInURL, saveLinkedInProfile, linkLinkedInProfileToContact, generateLinkedInMessage, saveLinkedInDraft, logLinkedInMessageSent, importLinkedInConversation, analyzeLinkedInReply, linkedInActions, linkedInState, updateLinkedInStatus, linkedInSendWarning, type LinkedInProfileInput } from "./linkedin";
import { confirmOutreachImport } from "./outreach-import";
import { dashboardMetrics } from "./provenance";

// In-memory fixtures only. Never persisted to a personal workspace or LinkedIn.
const db = createEmpty(); db.player.name = "Test Player";
const input: LinkedInProfileInput = { profileURL:"https://uk.linkedin.com/in/test-coach/?tracking=x",name:"Test Coach",club:"Test Club",role:"Academy Director",country:"Australia",headline:"User-provided headline",relevantRole:"Academy recruitment",source:"Profile viewed manually",lastChecked:"",notes:"Test only" };
assert.equal(canonicalLinkedInURL(input.profileURL), "https://www.linkedin.com/in/test-coach");
assert.throws(() => canonicalLinkedInURL("https://linkedin.com.evil.test/in/person"));
assert.throws(() => canonicalLinkedInURL("https://www.linkedin.com/company/club"));
const id = saveLinkedInProfile(db,input);
assert.equal(db.contacts.length,1); assert.equal(db.messages.length,0);
assert.equal(db.contacts[0].verifiedAt,null); assert.equal(db.contacts[0].confidence,"Unverified");
assert.equal(linkedInState(db.contacts[0],db).connectionConfirmed,false);
assert.equal(saveLinkedInProfile(db,{...input,profileURL:"https://www.linkedin.com/in/test-coach"}),id);
assert.equal(db.contacts.length,1);
const other = saveLinkedInProfile(db,{...input,profileURL:"https://linkedin.com/in/other-person",name:"Other Person"});
assert.throws(()=>linkLinkedInProfileToContact(db,other,input.profileURL), /belongs to/);
const message = generateLinkedInMessage(db,id,"Connection request","Shorter");
assert(message.includes("Test Club")); assert(message.length <= 200);
saveLinkedInDraft(db,id,message,"Connection request");
assert.equal(db.messages.filter(m=>m.status==="Sent").length,0); assert.equal(db.contacts[0].linkedInEvents?.length || 0,0);
assert.throws(()=>logLinkedInMessageSent(db,id,message,"Connection request","2026-01-01T12:00:00Z",false),/Confirm/);
logLinkedInMessageSent(db,id,message,"Connection request","2026-01-01T12:00:00Z",true);
assert.equal(db.messages.filter(m=>m.status==="Sent").length,1);
assert.equal(linkedInState(db.contacts[0],db).status,"Connection Request Sent");
assert.equal(linkedInState(db.contacts[0],db).connectionConfirmed,false);
assert(linkedInSendWarning(db,id,"Connection request",message).includes("already recorded"));
updateLinkedInStatus(db,id,"Connected","2026-01-02T12:00:00Z","Observed acceptance on LinkedIn");
assert.equal(linkedInState(db.contacts[0],db).connectionConfirmed,true);
assert.equal(linkedInState(db.contacts[0],db).connectedAt,"2026-01-02T12:00:00Z");
assert(linkedInActions(db).some(a=>a.contactId===id && a.title.includes("first message")));
const first=generateLinkedInMessage(db,id,"First message");
logLinkedInMessageSent(db,id,first,"First message","2026-01-03T12:00:00Z",true);
assert(linkedInSendWarning(db,id,"First message",first).includes("already recorded"));
const before=JSON.stringify(db);
const draft=importLinkedInConversation("Me: Hi Test Coach\nTest Coach: Contact Angelo. Please send your highlights.",db,id);
assert.equal(JSON.stringify(db),before,"Parsing must not save");
assert.equal(draft.platform,"LinkedIn");assert.equal(draft.referrals[0].name,"Angelo");assert.equal(draft.referrals[0].email,"");
draft.referrals[0].include=true;draft.referrals[0].club="Test Club";
confirmOutreachImport(db,[draft]);
assert.equal(db.contacts.length,3);assert.equal(db.referrals?.length,1);
assert.equal(db.contacts[0].linkedInProfile?.connectionConfirmed,true);
assert.equal(dashboardMetrics(db).find(m=>m.label==="Replies received")?.records.length,1);
assert(linkedInActions(db).some(a=>a.title.includes("Send highlights")));
assert(linkedInActions(db).some(a=>a.title.includes("Research Angelo")));
const count=db.messages.length;confirmOutreachImport(db,[draft]);assert.equal(db.messages.length,count);
assert.equal(analyzeLinkedInReply("Contact Angelo at angelo@example.test").personReferredTo,"Angelo");
assert.throws(()=>generateLinkedInMessage(db,id,"First message","Mention CV",first),/share link/);
const fresh=createEmpty();const freshId=saveLinkedInProfile(fresh,input);
const reply=importLinkedInConversation("Test Coach: Thanks for your message.",fresh,freshId);confirmOutreachImport(fresh,[reply]);
assert.equal(linkedInState(fresh.contacts[0],fresh).connectionConfirmed,false,"Replies never imply connection acceptance");
assert.equal(linkedInState(fresh.contacts[0],fresh).status,"Replied");
assert.throws(()=>logLinkedInMessageSent(fresh,freshId,"Hi [name]","First message","2026-01-01",true),/placeholders/);
console.log("PASS: manual profile review, identity matching, no fake verification/connections, draft isolation, manual sent confirmation, duplicate outreach protection, reviewed LinkedIn imports, referrals and stored-data actions.");
