import assert from "node:assert/strict";
import { createEmpty } from "@/data/empty";
import { parseConversation, parseCSV, confirmOutreachImport, validateImport, matchImportContact, normalizeIdentity } from "./outreach-import";
import { dashboardMetrics } from "./provenance";
import { profileContext, setupProgress } from "./player-profile";
import { generateOutreach } from "./intelligence";
// Test fixtures stay in memory, never in the user's workspace.
const db = createEmpty();
const parsed = parseConversation("Me:\nHello, here is my profile.\nJames Arrow:\nPlease email Angelo at example@club.com\nMe:\nThank you, I'll contact him.");
assert.equal(parsed.contactName, "James Arrow");
assert.deepEqual(parsed.messages.map(m => m.direction), ["out", "in", "out"]);
assert.equal(parsed.referrals[0].name, "Angelo");
assert.equal(parsed.email, "", "Referral email must not become sender email");
assert(parsed.messages.every(m => !m.date));
assert.throws(() => validateImport(parsed, db), /club/);
parsed.club = "TEST CLUB";
const first = confirmOutreachImport(db, [parsed]);
assert.deepEqual([first.contacts, first.messages], [1, 3]);
assert.deepEqual(dashboardMetrics(db).map(m => m.records.length), [1, 1, 2, 1, 1, 0]);
assert.equal(db.referrals?.length || 0, 0);
const repeat = confirmOutreachImport(db, [parseConversation("Me:\nHello, here is my profile.\nJames Arrow:\nPlease email Angelo at example@club.com\nMe:\nThank you, I'll contact him.")].map(p => ({ ...p, club: "TEST CLUB" })));
assert.equal(repeat.messages, 0);
assert.equal(repeat.contacts, 0);
const repeated = parseConversation("Me: Hello\nJames Arrow: Thanks\nMe: Hello\nJames Arrow: Thanks"); repeated.club = "REPEATED TEST CLUB";
const repeatDb = createEmpty(); confirmOutreachImport(repeatDb, [repeated]); assert.equal(repeatDb.messages.length, 4);
confirmOutreachImport(repeatDb, [repeated]); assert.equal(repeatDb.messages.length, 4, "Reimport preserves repeated utterances without duplicating the thread");
parsed.referrals[0].include = true;
parsed.referrals[0].club = "TEST CLUB";
confirmOutreachImport(db, [parsed]);
assert.equal(db.contacts.length, 2);
assert.equal(db.referrals?.length, 1);
assert.equal(db.contacts.find(c => c.name === "Angelo")?.email, "example@club.com");
confirmOutreachImport(db, [parsed]);
assert.equal(db.referrals?.length, 1);
const trial = parseConversation("Me: Can you review my profile?\nCoach: We are interested. Please join us for a trial.");
trial.contactName = "TEST TRIAL COACH"; trial.club = "TEST CLUB";
assert.equal(trial.createOpportunity, true); assert.equal(trial.opportunityStage, "Trial Discussion");
confirmOutreachImport(db, [trial]);
assert.equal(dashboardMetrics(db).at(-1)?.records.length, 1);
const noTrial = parseConversation("Coach: Unfortunately, we do not have any trial opportunities.");
assert.equal(noTrial.createOpportunity, false);
const email = parseConversation("From: Player <player@example.test>\nDate: 2026-01-01\nSubject: Football\nMy profile.\nFrom: Coach Smith <coach@example.test>\nDate: 2026-01-02\nSubject: Re: Football\nPlease send your CV.", { method: "Email", ownEmail: "player@example.test" });
assert.equal(email.email, "coach@example.test"); assert.equal(email.subject, "Football");
assert.deepEqual(email.messages.map(m => m.direction), ["out", "in"]);
assert.equal(email.messages[1].date, "2026-01-02T00:00:00.000Z");
const csv = parseCSV('club,country,league,contact,role,email,instagram,linkedin,platform,status,lastContacted,notes\r\n"TEST, CLUB",,,,Coach,test@example.test,@coach,,Instagram,Replied,2026-01-01,"Line one\nLine two"');
assert.equal(csv[0].notes, "Line one\nLine two"); assert.equal(csv[0].club, "TEST, CLUB");
assert.equal(csv[0].messages.length, 0, "CSV status does not fabricate messages");
assert.throws(() => parseCSV('club,contact\n"unclosed,name'), /Unclosed/);
assert.throws(() => parseCSV('club,contact,contact\na,b,c'), /duplicate/);
assert.equal(normalizeIdentity("https://www.instagram.com/Coach/", "instagram"), "coach");
assert.equal(normalizeIdentity("@Coach", "instagram"), "coach");
db.contacts[0].instagram = "https://instagram.com/coach/";
assert.equal(matchImportContact({ ...parsed, contactName: "New Name", club: "Other", instagram: "@COACH" }, db)?.id, db.contacts[0].id);
const unknown = parseConversation("Unstructured text without a sender label."); unknown.club = "TEST CLUB"; unknown.contactName = "Unknown";
assert.throws(() => validateImport(unknown, db), /directions/);
const copy = structuredClone(db);
copy.player.name = "TEST PLAYER"; copy.player.position = "Goalkeeper"; copy.player.currentClub = "TEST TEAM"; copy.player.achievementRecords = [{ id: "test", title: "Test title", team: "Test team", year: "2025", description: "Provided fact", importance: "High" }];
copy.player.travelAvailability = "Available in June";
assert(profileContext(copy.player).achievements.includes("Test title"));
assert(generateOutreach(copy.contacts[1], copy, "Email").includes("goalkeeper"));
assert.equal(setupProgress(createEmpty()).percent, 0);
console.log("PASS: parsing, review validation, deduplication, referrals, dates, CSV, real metrics, profile context and empty setup.");
